#!/usr/bin/env node
/**
 * #1322 · 词条表清单生成器（US1 加语言不改代码的数据清单一步）。
 *
 * 为什么需要它：词条入口（packages/<包>/src/entries/index.ts）不能运行期 readdir——
 *   ① base-render 的 entries 被大量 Node 渲染件 import，base-entries 的零依赖契约不许放扫描器；
 *   ② 7 个 plugin-* 的 entries/index.ts 被 tsdown 打进**浏览器束**，那里没有 node:fs。
 * 所以把「有哪些语言文件」编译期化：生成器扫词条目录，写两份**生成数据**：
 *   packages/<包>/src/entries/catalog.generated.ts   本包语言键 → 静态 import 的表
 *   packages/base-link-core/src/config/languages.generated.ts  全仓语言并集（AVAILABLE_LANGUAGES）
 * 加一门语言＝加词条文件＋重跑本生成器（pnpm gen），14 个 index.ts 与语言闭集都不改一行。
 *
 * 用法：
 *   node tooling/gen-entry-catalogs.mjs            # 写生成文件（pnpm gen 的第一步）
 *   node tooling/gen-entry-catalogs.mjs --check    # 只读核对（pnpm gen:check 的第一步）
 *
 * 生成文件是**数据**，不是逻辑；手工改会被 --check 判 stale。文件头有 @generated 标记。
 * 只认 .ts 词条表（.json 表先转成 .ts；JSON import 需要额外的 tsconfig 开关，本票不引）。
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { DEFAULT_LANGUAGE, entryLanguages, scanEntryTables } from './entry-languages.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '..');
const CHECK = process.argv.includes('--check');

const HEADER = '// @generated by tooling/gen-entry-catalogs.mjs — 不要手改；改词条文件后跑 pnpm gen。\n';

const jsSpecifier = (file) => './' + file.replace(/\.ts$/, '.js');

const ident = (lang) => lang.replace(/[^A-Za-z0-9_]/g, '_');

/** 一个包的 catalog.generated.ts 文本。 */
export function renderCatalog(pkg) {
  const langs = [...pkg.languages.keys()].sort((a, b) => {
    if (a === DEFAULT_LANGUAGE) return -1;
    if (b === DEFAULT_LANGUAGE) return 1;
    return a.localeCompare(b);
  });
  const imports = [];
  const aliases = new Map();
  for (const lang of langs) {
    const files = pkg.languages.get(lang);
    const list = [];
    for (let i = 0; i < files.length; i++) {
      const file = files[i];
      if (file.ext !== 'ts') throw new Error(pkg.pkg + ' 的 ' + file.file + ' 是 JSON 词条表；生成器只收 .ts（先转成 .ts）');
      if (!file.symbol) throw new Error(pkg.pkg + ' 的 ' + file.file + ' 里找不到 export const（表必须具名导出）');
      const alias = '_t_' + ident(lang) + '_' + i;
      imports.push("import { " + file.symbol + ' as ' + alias + " } from '" + jsSpecifier(file.file) + "';");
      list.push(alias);
    }
    aliases.set(lang, list);
  }
  const lines = [HEADER];
  lines.push('/** 本包词条表清单：语言键 → 词条文件导出的表；加语言文件后由 pnpm gen 重写本文件。 */');
  lines.push(...imports);
  lines.push('');
  for (const lang of langs) {
    const list = aliases.get(lang);
    if (list.length === 1) lines.push('const _' + ident(lang) + ' = ' + list[0] + ';');
    else lines.push('const _' + ident(lang) + ' = { ...' + list.join(', ...') + ' };');
  }
  lines.push('');
  lines.push('/** 词条表集合的窄类型（只引用各表导出，不把逐 key 字面量写进声明文件——TS7056 口径）。 */');
  lines.push('export type EntryTables = {');
  for (const lang of langs) {
    const list = aliases.get(lang);
    lines.push('  readonly ' + lang + ': ' + list.map((a) => 'typeof ' + a).join(' & ') + ';');
  }
  lines.push('};');
  lines.push('');
  lines.push('/** 本包词条表集合。 */');
  lines.push('export const ENTRY_TABLES: EntryTables = {');
  for (const lang of langs) lines.push('  ' + lang + ': _' + ident(lang) + ',');
  lines.push('};');
  return lines.join('\n') + '\n';
}

/** base-link-core 的语言清单生成文本。 */
export function renderRoster(root = ROOT) {
  const langs = entryLanguages(root);
  return HEADER
    + '/** 产品侧可用语言清单：所有包 src/entries 下语言文件的并集（基准语言第一，其余字母序）。 */\n'
    + 'export const AVAILABLE_LANGUAGES = [' + langs.map((l) => "'" + l + "'").join(', ') + '] as const;\n';
}

export function expectedFiles(root = ROOT) {
  const out = [];
  for (const pkg of scanEntryTables(root)) {
    out.push({ path: join(pkg.dir, 'catalog.generated.ts'), rel: 'packages/' + pkg.pkg + '/src/entries/catalog.generated.ts', text: renderCatalog(pkg) });
  }
  out.push({ path: join(root, 'packages', 'base-link-core', 'src', 'config', 'languages.generated.ts'), rel: 'packages/base-link-core/src/config/languages.generated.ts', text: renderRoster(root) });
  return out;
}

function main() {
  const files = expectedFiles(ROOT);
  if (CHECK) {
    const stale = [];
    for (const f of files) {
      if (!existsSync(f.path)) { stale.push(f.rel + '（缺文件）'); continue; }
      if (readFileSync(f.path, 'utf8') !== f.text) stale.push(f.rel);
    }
    if (stale.length > 0) {
      for (const s of stale) console.error('STALE ' + s);
      console.error('FAIL: 词条表清单不新鲜（' + stale.length + ' 件）；跑 pnpm gen 重生成，不许手改生成文件');
      process.exit(1);
    }
    console.log('RESULT: catalogs=' + files.length + ' stale=0');
    console.log('PASS: 词条表清单与词条目录一致（加语言文件后请跑 pnpm gen）');
    return;
  }
  for (const f of files) {
    mkdirSync(dirname(f.path), { recursive: true });
    writeFileSync(f.path, f.text, 'utf8');
    console.log('WROTE ' + f.rel);
  }
  console.log('RESULT: catalogs=' + files.length + ' languages=' + entryLanguages(ROOT).join('+'));
}

const isEntry = process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isEntry) main();
