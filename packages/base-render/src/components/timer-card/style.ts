/** timer-card · **样式段**（本件唯一的样式来源）。
 *
 *  三条纪律（与组件层其余件同一份）：
 *   1. 颜色／圆角／字面／字号一律经 `skinVar()` 读；本件源码里不出现手写的 `var(--ilife-…)`；
 *   2. 全部规则 scope 在 `.<prefix>page-ui` 之下；
 *   3. **状态靠「字 ＋ 形 ＋ 色」**：状态字（待开始／计时中／已暂停／到点了）＋ 标签形状
 *      （底线／实底块／描边空心／双线框）＋ 色 ⇒「大字报刊」皮肤下强调色＝墨黑也分得出。
 *
 *  交互件的地板（判据逐条断）：
 *   · 按钮命中盒 **≥44 高**、`min-width` 锁住（`TIMER_CARD_BUTTON_MIN_WIDTH_PX`）⇒
 *     「开始／暂停／继续／重新开始／开始中…」五种字换来换去**不跳版**；
 *   · 进度条只动 `transform: scaleX()`（不动宽度）；`:hover` 包在设备能力查询里且不是唯一通路；
 *   · `:active` 只动 `transform`（≤80ms）；`:focus-visible` 有 2px 可见焦点环；
 *   · `disabled` 有 `cursor:not-allowed`；`prefers-reduced-motion` 下过渡关掉、读数照走（不卡半路）；
 *   · 状态不依赖 `transitionend`（读数由运行时按时间写，不靠动画收尾）。
 *
 *  几何契约：大数字 `white-space:nowrap`（时间**永不截断**）；窄宽由**容器**决定。
 */
import { skinVar } from '../skin/contract.js';
import { timerCardClass, timerCardSlot, type TimerCardSlot } from './attrs.js';

/** 换行（仓库口径：不写字面换行转义）。 */
const LF = String.fromCharCode(10);

/** 本件的内容容器名（`@container` 按它命中）。 */
export const TIMER_CARD_CONTAINER = 'ilife-timer-card';
/** 窄档断点（px）：容器窄于它就让按钮各占一整行（**不是**视口断点）。 */
