/** 按钮的宽度下限（px）：主按钮换字（开始／暂停／继续／重新开始／开始中…）时不跳版。 */
export const TIMER_CARD_BUTTON_MIN_WIDTH_PX = 112;
/** 大数字的字号（px）：一个显示级读数（与正文字号的比例 ≫2×）。 */
export const TIMER_CARD_VALUE_PX = 44;

