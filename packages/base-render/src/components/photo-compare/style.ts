export const PHOTO_COMPARE_STAGE_MAX_PX = 460;

/** 四角取景角标：8 层背景（每角一横一竖），不加元素、不用伪元素。 */
function marksCss(): string[] {
  const color = skinVar('line');
  const bar = 'linear-gradient(' + color + ', ' + color + ')';
  const arm = String(PHOTO_COMPARE_MARK_ARM_PX) + 'px';
  const thick = String(PHOTO_COMPARE_MARK_THICK_PX) + 'px';
  const inset = String(PHOTO_COMPARE_MARK_INSET_PX) + 'px';
  const right = 'calc(100% - ' + inset + ')';
  const bottom = 'calc(100% - ' + inset + ')';
  const pos: string[] = [];
  for (const [y, x] of [[inset, inset], [inset, right], [bottom, inset], [bottom, right]]) {
    pos.push(x + ' ' + y, x + ' ' + y);
  }
  const size = [arm + ' ' + thick, thick + ' ' + arm].join(', ');
  return [
    '  background-image: ' + new Array(8).fill(bar).join(', ') + ';',
    '  background-size: ' + new Array(4).fill(size).join(', ') + ';',
    '  background-position: ' + pos.join(', ') + ';',
    '  background-repeat: no-repeat;',
  ];
}

