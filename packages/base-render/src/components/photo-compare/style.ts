/** photo-compare · **样式段**（本件唯一的样式来源）。**重做件**：拖动之外还要给得出「变了多少」。
 *
 *  四条重做口径（`重做设计口径.md` §0）逐条落在这一段里：
 *   ① **占位物读得出它是什么**：定形框（`aspect-ratio`）＋ 四角取景角标 ＋ 中央相机记号 ＋ 题注条；
 *   ② **状态除色之外还有第二样**：差值行有**方向记号（↓／↑／＝）**与**正负号**，颜色只是第三样；
 *   ③ **层次不靠投影与圆角**：台面靠一圈发丝线，题注条靠软底色，差值行靠**发丝线 ＋ 缩进**；
 *   ④ **骨架对得上这类数据**：`<figure>` 装照片、`<ul>` 装差值行（一件就是「两张图 ＋ N 行差值」）。
 *
 *  两档是**同一份标记**：宽档两张叠着（`grid-area: 1/1` ＋ 裁切），窄档同一对 `<figure>` 左右并排，
 *  拖动条收起、差值条上屏。判的是**本件自己的宽度**（`@container`），不是视口宽度。
 *
 *  纪律：只经 `skinVar()` 读皮肤；scope 在 `.<prefix>page-ui` 之下；零 `:root`／`!important`；
 *  媒体查询只判设备能力（`hover`／`prefers-reduced-motion`）。
 */
