/** 动作按钮的宽度下限（px）：换字（开始／处理中）时不跳版。 */
export const DUE_ROW_BUTTON_MIN_WIDTH_PX = 104;
/** 倒计时读数的字号（px）：一个显示级读数（与正文字号的比例 ≥4×）。 */
