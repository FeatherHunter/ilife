/** due-row · **样式段**（本件唯一的样式来源）。
 *
 *  三条纪律（与组件层其余件同一份）：
 *   1. 颜色／圆角／字面／字号一律经 `skinVar()` 读；本件源码里不出现手写的 `var(--ilife-…)`；
 *   2. 全部规则 scope 在 `.<prefix>page-ui` 之下；
 *   3. **三档靠「字 ＋ 形 ＋ 色」**：左竖条实线／点线／双线，档位字带底线／描边实底／双线框，
 *      点圆／方／菱 ⇒「大字报刊」皮肤下强调色＝墨黑也分得出紧急度。
 *
 *  交互件的地板（判据逐条断）：
 *   · 动作是真 `<button>`，命中盒 **≥44 高**、`min-width` 锁住（`DUE_ROW_BUTTON_MIN_WIDTH_PX`）
 *     ⇒ 开始／处理中／禁用三档换字**不跳版**；
 *   · `:hover` 包在 `@media (hover:hover) and (pointer:fine)` 里、且**不是唯一通路**；
 *   · `:active` 只动 `transform`（≤80ms）；`:focus-visible` 有 2px 可见焦点环；
 *   · `disabled` 有 `cursor:not-allowed`（为什么不能按写在按钮旁的 `note` 上）；
 *   · `prefers-reduced-motion` 下过渡关掉、状态照落（不许有东西卡在半路）；状态不依赖 `transitionend`。
 *
 *  几何契约：倒计时（放大的数）与到期日 `white-space:nowrap`、**永不截断**；
 *  窄宽由**容器**决定（`container-type:inline-size` ＋ `@container`），不看视口。
 */
import { skinVar } from '../skin/contract.js';
import { dueRowClass, dueRowSlot, type DueRowSlot } from './attrs.js';

/** 换行（仓库口径：不写字面换行转义）。 */
const LF = String.fromCharCode(10);

/** 本件的内容容器名（`@container` 按它命中）。 */
export const DUE_ROW_CONTAINER = 'ilife-due-row';
/** 窄档断点（px）：容器窄于它就把右侧那一块（倒计时 ＋ 动作）放到下一行（**不是**视口断点）。 */
