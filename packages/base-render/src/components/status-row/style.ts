/** 行高下限（px）：44 是全仓的触控地板；本件没有可点元素，行高先钉在这里。 */
export const STATUS_ROW_ITEM_MIN_HEIGHT_PX = 44;
/** 行内上下内距（px）：换算连线与点的位置时用它（别处不许再写这个数）。 */
