/** status-row · **样式段**（本件唯一的样式来源）。
 *
 *  三条纪律（与组件层其余件同一份）：
 *   1. 颜色／圆角／阴影／字面／字号**一律经 `skinVar()` 读**（产出带兜底链的 `var()` 串，
 *      老页面没挂皮肤时落到那 11 个冻结 token）——本件源码里**不出现**手写的 `var(--ilife-…)`；
 *   2. 全部规则 scope 在 `.<prefix>page-ui` 之下（不开 pageUi 的页零命中 ⇒ 加法式）；
 *   3. **状态靠「字 ＋ 形 ＋ 色」三样一起**给：徽标与轨道点的形状差异逐档写在下面
 *      （空心圆／双环实心／实心圆／空心方／双线菱；无框底线／空心框／实底色块／框＋底块／双线框），
 *      所以「大字报刊」（强调色＝墨黑）那档也分得开。
 *
 *  几何契约（钉在判据里）：
 *   · 行高 ≥ `STATUS_ROW_ITEM_MIN_HEIGHT_PX`（44）：本件没有可点元素，但行高先钉在这个地板上，
 *     页面把整行接成入口时不会掉到 44 以下；
 *   · 金额与到期日**永不 `…` 截断**（`white-space:nowrap`，不写 `overflow:hidden`）；
 *   · 窄宽由**容器**决定（`container-type:inline-size` ＋ `@container`），不看视口：
 *     本件会被嵌进侧栏／面板／卡片，视口宽 ≠ 组件宽。本件**零动效**（没有可卡住的中间态）。
 */
import { skinVar } from '../skin/contract.js';
import { statusRowClass, statusRowSlot, type StatusRowSlot } from './attrs.js';

/** 换行（仓库口径：不写字面换行转义）。 */
const LF = String.fromCharCode(10);

/** 本件的内容容器名（`@container` 按它命中，不会跟别件的容器串味）。 */
