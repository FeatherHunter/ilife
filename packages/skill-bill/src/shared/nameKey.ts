/** #1280 · 值的**比较键**（本件只有一个纯函数，住共用位：写入域与它的判据都在用）。
 *
 *  是什么：把「两种看起来不同的写法、其实是同一个值」折成同一串——`NFKC` 归一（全角折半角，
 *  如 `／`→`/`、全角字母→半角字母）→ 去首尾空白 → 内部连续空白折成一个半角空格 → 转小写。
 *
 *  干什么：**只在「两个值是不是同一个」这一步用它**。写入域落库前的去重收口拿它把用户敲的值与
 *  库里已有的分类／账本对齐：按本键相等就落**库里已有那个拼写**，不等才原样落库
 *  （见 `src/write/record.ts` 的 `canonicalizeExistingNames`）。
 *
 *  **只用于比较**：任何一处落库的拼写都不许拿本键当值写回去——写回去的永远是库里已有那个原串
 *  （键是小写折叠后的串，本身不是能给用户看的写法）。
 *
 *  不做的语义：只折大小写、首尾与内部空白、全角半角三样，**不做近义合并**（`午饭` 与 `午餐`
 *  仍是两个值）、不拆层级、不认前缀。
 *
 *  谁在用（指名）：`src/write/record.ts`（`existingSpellingOf` 那一步的比较键）；
 *  判据 `test/t1280-值级放开护栏.test.mjs`（全角斜线与大小写两组等价写法）。 */
export function nameKey(raw: string): string {
  return String(raw).normalize('NFKC').trim().replace(/\s+/g, ' ').toLowerCase();
}
