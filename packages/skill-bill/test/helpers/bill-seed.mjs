/**
 * 把夹具记录写成一个全新的 SQLite 库（`dir/<DB_FILENAME>`）。
 *
 * @param {string} dir 库目录（调用方建好：测试一律是临时目录 ＋ `bill.yaml` 落点基座）
 * @param {ReadonlyArray<ReadonlyArray<string | number>>} [records] 记录集（缺省＝`SEED_RECORDS`）
 * @returns {string} 库文件绝对路径
 */
export function seedBillDb(dir, records = SEED_RECORDS) {
  if (typeof dir !== 'string' || dir.trim() === '') throw new Error('seedBillDb 需要一个目录');
  const dbPath = join(dir, SEED_DB_FILENAME);
  if (existsSync(dbPath)) throw new Error('seedBillDb 只写新库：这个路径下已经有库了 ' + dbPath);
  const db = new DatabaseSync(dbPath);
  try {
    db.exec(DDL);
    const stmt = db.prepare(
      'INSERT INTO bills (category, time, amount, account, ledger, currency, note) VALUES (?, ?, ?, ?, ?, ?, ?)',
    );
    for (const [time, category, amount, account, ledger, note] of records) {
      stmt.run(category, time, amount, account, ledger, '人民币', note);
    }
  } finally {
    db.close();
  }
  return dbPath;
}
